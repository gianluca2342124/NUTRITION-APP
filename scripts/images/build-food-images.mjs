#!/usr/bin/env node
/**
 * Builds the curated food image set from Wikimedia Commons.
 *
 *   node scripts/images/build-food-images.mjs
 *
 * Input:  data/food-images/curation.json  (hand-picked, visually reviewed files)
 * Output: apps/web/public/food-images/<key>-square.webp (512×512)
 *         apps/web/public/food-images/<key>-wide.webp   (960×720, 4:3)
 *         packages/data/src/food-images.generated.ts   (manifest + credits)
 *
 * Every file's licence is re-checked against an allowlist of free licences;
 * anything else is skipped. Images are cropped and resized (noted in the
 * credits, as CC BY / BY-SA require), never retouched.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT_DIR = join(ROOT, 'apps/web/public/food-images');
const MANIFEST = join(ROOT, 'packages/data/src/food-images.generated.ts');
const UA = 'FudyuImageCurator/1.0 (curated food photos; https://github.com/gianluca2342124/nutrition-app)';
const ALLOWED = /^(CC0|Public domain|CC BY(-SA)? (2\.0|2\.5|3\.0|4\.0))/i;

const curation = JSON.parse(readFileSync(join(ROOT, 'data/food-images/curation.json'), 'utf8'));
mkdirSync(OUT_DIR, { recursive: true });

const stripHtml = (s) => (s ?? '').replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim();

async function info(file) {
  const params = new URLSearchParams({
    action: 'query', format: 'json', formatversion: '2', titles: file,
    prop: 'imageinfo', iiprop: 'url|extmetadata|size', iiurlwidth: '1280',
  });
  const res = await fetch(`https://commons.wikimedia.org/w/api.php?${params}`, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Commons API ${res.status}`);
  const page = (await res.json()).query.pages[0];
  const ii = page.imageinfo?.[0];
  if (!ii) throw new Error(`missing file ${file}`);
  const m = ii.extmetadata ?? {};
  return {
    thumb: ii.thumburl,
    pageUrl: ii.descriptionurl,
    license: stripHtml(m.LicenseShortName?.value),
    licenseUrl: m.LicenseUrl?.value ?? null,
    author: stripHtml(m.Artist?.value) || 'Unknown author',
  };
}

async function download(url) {
  for (let attempt = 0; attempt < 4; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
    await new Promise((r) => setTimeout(r, 2000 * (attempt + 1)));
  }
  throw new Error(`download failed: ${url}`);
}

const manifest = {};
for (const [key, entry] of Object.entries(curation.foods)) {
  const meta = await info(entry.file);
  if (!ALLOWED.test(meta.license)) {
    console.warn(`skip ${key}: licence "${meta.license}" not allowed`);
    continue;
  }
  const source = await download(meta.thumb);
  const position = entry.position ?? sharp.strategy.attention;
  await sharp(source).resize(512, 512, { fit: 'cover', position }).webp({ quality: 78 }).toFile(join(OUT_DIR, `${key}-square.webp`));
  await sharp(source).resize(960, 720, { fit: 'cover', position }).webp({ quality: 76 }).toFile(join(OUT_DIR, `${key}-wide.webp`));
  manifest[key] = {
    square: `/food-images/${key}-square.webp`,
    wide: `/food-images/${key}-wide.webp`,
    credit: {
      title: entry.file.replace(/^File:/, ''),
      author: entry.author ?? meta.author,
      license: meta.license,
      licenseUrl: meta.licenseUrl,
      sourceUrl: meta.pageUrl,
      source: 'Wikimedia Commons',
      changes: 'cropped and resized',
    },
  };
  console.log(`ok ${key} (${meta.license})`);
}

const header = `// Generated by scripts/images/build-food-images.mjs — do not edit by hand.\n// Curated, licence-checked photos for generic foods (key = generic food slug).\n`;
const body = `import type { CuratedImage } from './images';\n\nexport const CURATED_FOOD_IMAGES: Record<string, CuratedImage> = ${JSON.stringify(manifest, null, 2)};\n`;
writeFileSync(MANIFEST, header + body);
console.log(`wrote ${Object.keys(manifest).length} images`);
